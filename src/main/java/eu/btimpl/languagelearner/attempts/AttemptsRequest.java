package eu.btimpl.languagelearner.attempts;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/** A batch of answers as the app uploads it. */
@Schema(name = "AttemptsRequest")
public record AttemptsRequest(
    @Schema(
            description =
                "The answers, at most " + AttemptsRequest.MAX_ATTEMPTS + " in one request")
        @NotNull
        @Size(max = AttemptsRequest.MAX_ATTEMPTS)
        List<@NotNull @Valid Item> attempts) {

  public static final int MAX_ATTEMPTS = 500;

  /** One answer. */
  @Schema(name = "AttemptItem")
  public record Item(
      @Schema(description = "Generated by the app; an id the server knows is skipped") @NotNull
          UUID id,
      @Schema(description = "Id of the deck, from GET /api/v1/decks") @NotBlank String deckId,
      @Schema(description = "Id of the word, from GET /api/v1/decks") @NotBlank String wordId,
      @NotNull Mode mode,
      @NotNull Outcome outcome,
      @Schema(description = "When the student answered, by the clock of the phone") @NotNull
          Instant answeredAt) {}
}
